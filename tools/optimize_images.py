#!/usr/bin/env python3
"""Prepare photos for the site.

Resizes, fixes rotation, strips metadata (including GPS) and saves web-ready
JPEGs into img/<section>/. For the archive it also rebuilds assets/archivio.js.

Usage (from the repo root):
    pip3 install pillow
    python3 tools/optimize_images.py ~/Desktop/foto-archivio archivio
    python3 tools/optimize_images.py ~/Desktop/siculo siculo
    python3 tools/optimize_images.py --manifest-only      # just rebuild archivio.js

Archive photos keep their file name; project photos are renamed cover.jpg,
01.jpg, 02.jpg ... as the pages expect (a file named "cover..." becomes the cover).

Sections: archivio, boheme, modi, siculo, faccioni, place-of-freedom,
papa-che-fanno-i-papa, about. Originals are never modified.
"""
import argparse
import json
import re
import sys
from pathlib import Path

try:
    from PIL import Image, ImageOps
except ImportError:
    sys.exit("Pillow is missing: run  pip3 install pillow")

ROOT = Path(__file__).resolve().parent.parent
IMG = ROOT / "img"
MANIFEST = ROOT / "assets" / "archivio.js"
EXTS = {".jpg", ".jpeg", ".png", ".tif", ".tiff", ".webp", ".heic"}
MAX_SIDE = 2000      # px, long side
QUALITY = 82

HEADER = """// Archive photos, shown at random on archivio.html.
// Generated by tools/optimize_images.py: re-run it after adding photos to img/archivio/.
// You can edit title / camera / film / year / alt by hand: they are kept on the next run.
"""


def slug(name):
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s or "foto"


def process(src, dest_dir, name):
    dest = dest_dir / (name + ".jpg")
    with Image.open(src) as im:
        im = ImageOps.exif_transpose(im)
        if im.mode not in ("RGB", "L"):
            im = im.convert("RGB")
        im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
        # No exif/icc passed -> metadata (camera serial, GPS) is dropped.
        im.save(dest, "JPEG", quality=QUALITY, optimize=True, progressive=True)
    return dest


def read_manifest():
    if not MANIFEST.exists():
        return {}
    text = MANIFEST.read_text(encoding="utf-8")
    m = re.search(r"window\.ARCHIVIO\s*=\s*(\[.*\])\s*;", text, re.S)
    if not m:
        return {}
    try:
        return {p["src"]: p for p in json.loads(m.group(1)) if p.get("src")}
    except json.JSONDecodeError:
        print("! assets/archivio.js is not plain JSON, existing captions not kept")
        return {}


def write_manifest():
    old = read_manifest()
    files = sorted(p for p in (IMG / "archivio").iterdir()
                   if p.suffix.lower() in {".jpg", ".jpeg", ".webp", ".png"})
    photos = []
    for f in files:
        src = f"img/archivio/{f.name}"
        entry = old.get(src, {"src": src})
        entry.setdefault("alt", "Fotografia analogica di Simone Carducci")
        photos.append(entry)
    body = json.dumps(photos, ensure_ascii=False, indent=2)
    MANIFEST.write_text(f"{HEADER}window.ARCHIVIO = {body};\n", encoding="utf-8")
    print(f"assets/archivio.js: {len(photos)} photos")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", nargs="?", help="folder (or single file) with the original photos")
    ap.add_argument("section", nargs="?", default="archivio", help="destination folder inside img/")
    ap.add_argument("--manifest-only", action="store_true")
    args = ap.parse_args()

    if not args.manifest_only:
        if not args.source:
            ap.error("source folder is required")
        src = Path(args.source).expanduser()
        items = [src] if src.is_file() else sorted(
            p for p in src.rglob("*") if p.suffix.lower() in EXTS and not p.name.startswith("."))
        if not items:
            sys.exit(f"No photos found in {src}")
        dest_dir = IMG / args.section
        dest_dir.mkdir(parents=True, exist_ok=True)
        total = 0
        # Project pages expect cover.jpg + 01.jpg, 02.jpg ... (in name order).
        # A file whose name starts with "cover" becomes the cover; otherwise the first one.
        numbered = args.section != "archivio"
        if numbered:
            covers = [p for p in items if p.stem.lower().startswith("cover")]
            cover = covers[0] if covers else items[0]
            rest = [p for p in items if p is not cover]
            names = [(cover, "cover")] + [(p, f"{i:02d}") for i, p in enumerate(rest, 1)]
        else:
            names = [(p, slug(p.stem)) for p in items]
        for p, name in names:
            try:
                out = process(p, dest_dir, name)
            except Exception as e:  # unreadable file (e.g. HEIC without plugin)
                print(f"! skipped {p.name}: {e}")
                continue
            kb = out.stat().st_size // 1024
            total += kb
            print(f"  {p.name} -> {out.relative_to(ROOT)} ({kb} KB)")
        print(f"{len(items)} photos, {total / 1024:.1f} MB total")

    if args.manifest_only or args.section == "archivio":
        write_manifest()


if __name__ == "__main__":
    main()
